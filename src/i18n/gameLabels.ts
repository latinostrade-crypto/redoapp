/** Only for app-owned labels and ledger event names, never player names. */
export function translateGameLabel(value: string, translate: (key: MessageKey, values?: MessageValues) => string) {
  const patterns: Array<[RegExp, MessageKey, string[]]> = [
    [/^Check-in Day (\d+)$/, 'checkinDayEvent', ['day']],
    [/^Daily Check-in \(Day (\d+)\)$/, 'dailyCheckinEvent', ['day']],
    [/^Daily Streak Day (\d+) Refill$/, 'dailyStreakRefillEvent', ['day']],
    [/^L(\d+) Referral Match Bonus$/, 'referralMatchEvent', ['level']],
    [/^L(\d+) (Poker|Blackjack) Cash-out Referral Bonus$/, 'referralCashoutEvent', ['level', 'game']],
  ];
  for (const [pattern, key, names] of patterns) {
    const found = pattern.exec(value);
    if (found) return translate(key, Object.fromEntries(names.map((name, index) => [name, found[index + 1]])));
  }
  const key = gameLabelKeys[value as keyof typeof gameLabelKeys];
  return key ? translate(key) : value;
}
